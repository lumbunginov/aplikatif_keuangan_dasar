    public static function getMainNavItems()
    {
        $items = [];

        $items[] = [
            'icon' => 'dashboard',
            'name' => 'Dashboard',
            'path' => '/dashboard',
        ];

        if (self::can('view users')) {
            $items[] = [
                'icon' => 'user-profile',
                'name' => 'Users',
                'path' => '/users',
            ];
        }

        if (self::can('view roles')) {
            $items[] = [
                'icon' => 'authentication',
                'name' => 'Roles',
                'path' => '/roles',
            ];
        }

        if (Auth::check() && Auth::user()->hasRole('superadmin')) {
            $items[] = [
                'icon' => 'settings',
                'name' => 'Settings',
                'path' => '/settings',
            ];
        }

        if (self::can('view activity-log')) {
            $items[] = [
                'icon' => 'tables',
                'name' => 'Activity Log',
                'path' => '/activity-log',
            ];
        }

        return $items;
    }

    public static function getMenuGroups()
    {
        return [
            [
                'title' => 'Menu',
                'items' => self::getMainNavItems()
            ],
        ];
    }

    private static function can(string $permission): bool
    {
        return Auth::check() && Auth::user()->can($permission);
    }

    public static function isActive($path)
    {
        return request()->is(ltrim($path, '/'));
    }

